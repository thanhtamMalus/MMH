AES::AES(const Bytes& key) : rounds_(0) {
    if (key.size() != 16 && key.size() != 24 && key.size() != 32) {
        throw std::invalid_argument("AES key must be 128, 192, or 256 bits");
    }
    const std::size_t key_words = key.size() / 4;
    rounds_ = key_words + 6;
    const std::size_t expanded_size = 16 * (rounds_ + 1);
    round_keys_.resize(expanded_size);
    std::copy(key.begin(), key.end(), round_keys_.begin());

    std::uint8_t rcon = 1;
    std::array<std::uint8_t, 4> temporary{};
    for (std::size_t generated = key.size(); generated < expanded_size; generated += 4) {
        for (std::size_t i = 0; i < 4; ++i) {
            temporary[i] = round_keys_[generated - 4 + i];
        }
        const std::size_t word_index = generated / 4;
        if (word_index % key_words == 0) {
            const std::uint8_t first = temporary[0];
            temporary[0] = sbox[temporary[1]];
            temporary[1] = sbox[temporary[2]];
            temporary[2] = sbox[temporary[3]];
            temporary[3] = sbox[first];
            temporary[0] ^= rcon;
            rcon = multiply(rcon, 2);
        } else if (key_words == 8 && word_index % key_words == 4) {
            for (auto& value : temporary) {
                value = sbox[value];
            }
        }
        for (std::size_t i = 0; i < 4; ++i) {
            round_keys_[generated + i] =
                static_cast<std::uint8_t>(round_keys_[generated - key.size() + i] ^ temporary[i]);
        }
    }
}

Block AES::encrypt(const Block& input) const {
    Block state = input;
    add_round_key(state, round_keys_, 0);
    for (std::size_t round = 1; round < rounds_; ++round) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, round_keys_, round);
    }
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, round_keys_, rounds_);
    return state;
}

Block AES::decrypt(const Block& input) const {
    Block state = input;
    add_round_key(state, round_keys_, rounds_);
    for (std::size_t round = rounds_ - 1; round > 0; --round) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, round_keys_, round);
        inv_mix_columns(state);
    }
    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, round_keys_, 0);
    return state;
}

Bytes pad(const Bytes& input) {
    const std::size_t padding_length = 16 - (input.size() % 16);
    Bytes output = input;
    output.insert(output.end(), padding_length, static_cast<std::uint8_t>(padding_length));
    return output;
}

Bytes unpad(const Bytes& input) {
    if (input.empty() || input.size() % 16 != 0) {
        throw std::invalid_argument("PKCS#7 input must contain complete blocks");
    }
    const std::uint8_t padding_length = input.back();
    if (padding_length == 0 || padding_length > 16 || padding_length > input.size()) {
        throw std::invalid_argument("Invalid PKCS#7 padding length");
    }
    std::uint8_t difference = 0;
    for (std::size_t i = 0; i < padding_length; ++i) {
        difference |= static_cast<std::uint8_t>(input[input.size() - 1 - i] ^ padding_length);
    }
    if (difference != 0) {
        throw std::invalid_argument("Invalid PKCS#7 padding bytes");
    }
    return Bytes(input.begin(), input.end() - padding_length);
}

Block xorblock(const Block& lhs, const Block& rhs) {
    Block result{};
    for (std::size_t i = 0; i < result.size(); ++i) {
        result[i] = static_cast<std::uint8_t>(lhs[i] ^ rhs[i]);
    }
    return result;
}

void check_iv(const Bytes& iv) {
    if (iv.size() != 16) {
        throw std::invalid_argument("IV must contain exactly 16 bytes");
    }
}

void check_aligned(const Bytes& input) {
    if (input.size() % 16 != 0) {
        throw std::invalid_argument("Input length must be a multiple of 16 bytes");
    }
}

void append(Bytes& destination, const Bytes& source) {
    destination.insert(destination.end(), source.begin(), source.end());
}

void append(Bytes& destination, const Block& source) {
    destination.insert(destination.end(), source.begin(), source.end());
}

Block block(const Bytes& input, std::size_t offset) {
    if (offset > input.size() || input.size() - offset < 16) {
        throw std::out_of_range("Requested block is outside the byte array");
    }
    Block result{};
    std::copy_n(input.begin() + static_cast<std::ptrdiff_t>(offset), result.size(), result.begin());
    return result;
}

