std::uint8_t multiply(std::uint8_t a, std::uint8_t b) {
    std::uint8_t result = 0;
    for (unsigned int i = 0; i < 8; ++i) {
        if ((b & 1U) != 0U) {
            result ^= a;
        }
        const bool high_bit = (a & 0x80U) != 0U;
        a = static_cast<std::uint8_t>(a << 1U);
        if (high_bit) {
            a ^= 0x1bU;
        }
        b = static_cast<std::uint8_t>(b >> 1U);
    }
    return result;
}

void add_round_key(Block& state, const std::vector<std::uint8_t>& keys, std::size_t round) {
    const std::size_t offset = round * 16;
    for (std::size_t i = 0; i < state.size(); ++i) {
        state[i] ^= keys[offset + i];
    }
}

void sub_bytes(Block& state) {
    for (auto& value : state) {
        value = sbox[value];
    }
}

void inv_sub_bytes(Block& state) {
    for (auto& value : state) {
        value = inv_sbox[value];
    }
}

void shift_rows(Block& state) {
    const Block original = state;
    for (std::size_t row = 0; row < 4; ++row) {
        for (std::size_t column = 0; column < 4; ++column) {
            state[row + 4 * column] = original[row + 4 * ((column + row) % 4)];
        }
    }
}

void inv_shift_rows(Block& state) {
    const Block original = state;
    for (std::size_t row = 0; row < 4; ++row) {
        for (std::size_t column = 0; column < 4; ++column) {
            state[row + 4 * column] = original[row + 4 * ((column + 4 - row) % 4)];
        }
    }
}

void mix_columns(Block& state) {
    for (std::size_t column = 0; column < 4; ++column) {
        const std::size_t i = column * 4;
        const std::uint8_t a = state[i], b = state[i + 1], c = state[i + 2], d = state[i + 3];
        state[i]     = static_cast<std::uint8_t>(multiply(a, 2) ^ multiply(b, 3) ^ c ^ d);
        state[i + 1] = static_cast<std::uint8_t>(a ^ multiply(b, 2) ^ multiply(c, 3) ^ d);
        state[i + 2] = static_cast<std::uint8_t>(a ^ b ^ multiply(c, 2) ^ multiply(d, 3));
        state[i + 3] = static_cast<std::uint8_t>(multiply(a, 3) ^ b ^ c ^ multiply(d, 2));
    }
}

void inv_mix_columns(Block& state) {
    for (std::size_t column = 0; column < 4; ++column) {
        const std::size_t i = column * 4;
        const std::uint8_t a = state[i], b = state[i + 1], c = state[i + 2], d = state[i + 3];
        state[i]     = static_cast<std::uint8_t>(multiply(a, 14) ^ multiply(b, 11) ^ multiply(c, 13) ^ multiply(d, 9));
        state[i + 1] = static_cast<std::uint8_t>(multiply(a, 9) ^ multiply(b, 14) ^ multiply(c, 11) ^ multiply(d, 13));
        state[i + 2] = static_cast<std::uint8_t>(multiply(a, 13) ^ multiply(b, 9) ^ multiply(c, 14) ^ multiply(d, 11));
        state[i + 3] = static_cast<std::uint8_t>(multiply(a, 11) ^ multiply(b, 13) ^ multiply(c, 9) ^ multiply(d, 14));
    }
}

